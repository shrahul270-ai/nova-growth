const LOCAL_STORAGE_KEY = "nova_custom_publishers";

export function getCustomPublishers(): PublisherSite[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveCustomPublisher(site: PublisherSite): PublisherSite[] {
  if (typeof window === "undefined") return [];
  try {
    const existing = getCustomPublishers();
    const updated = [site, ...existing.filter((s) => s.id !== site.id && s.domain !== site.domain)];
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
    // Dispatch storage event for instant reactive update across tabs/components
    window.dispatchEvent(new Event("publishers-updated"));
    return updated;
  } catch {
    return [];
  }
}

export function deleteCustomPublisher(id: string): PublisherSite[] {
  if (typeof window === "undefined") return [];
  try {
    const existing = getCustomPublishers();
    const updated = existing.filter((s) => s.id !== id);
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
    window.dispatchEvent(new Event("publishers-updated"));
    return updated;
  } catch {
    return [];
  }
}

export function getAllPublishers(): PublisherSite[] {
  const custom = getCustomPublishers();
  return [...custom, ...INITIAL_PUBLISHERS];
}
