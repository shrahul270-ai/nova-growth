const CUSTOM_STORAGE_KEY = "nova_growth_custom_publishers_v1";

export function getCustomPublishers(): PublisherSite[] {
  if (typeof window === "undefined") return [];
  try {
    const data = localStorage.getItem(CUSTOM_STORAGE_KEY);
    return data ? JSON.parse(data) : [];
  } catch {
    return [];
  }
}

export function saveCustomPublisher(site: PublisherSite): void {
  if (typeof window === "undefined") return;
  const existing = getCustomPublishers();
  const updated = [site, ...existing];
  localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(updated));
}

export function deleteCustomPublisher(id: string): void {
  if (typeof window === "undefined") return;
  const existing = getCustomPublishers();
  const updated = existing.filter((p) => p.id !== id);
  localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(updated));
}
